#!/usr/bin/env node
/**
 * Convierte archivos Markdown a HTML para la documentación
 * Esto permite que los enlaces en el README funcionen correctamente
 */

import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';
import { marked } from 'marked';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const DOCS_DIR = path.join(rootDir, 'docs', 'jsdoc');

// Leer la plantilla de navegación de un archivo JSDoc existente
async function getNavigationTemplate() {
    const indexPath = path.join(DOCS_DIR, 'index.html');
    const indexContent = await fs.readFile(indexPath, 'utf-8');
    
    // Extraer la navegación (desde <nav> hasta </nav>)
    const navStart = indexContent.indexOf('<nav class="wrap">');
    const navEnd = indexContent.indexOf('</nav>', navStart) + 6;
    const navigation = indexContent.substring(navStart, navEnd);
    
    // Extraer el header (input checkbox y labels)
    const headerStart = indexContent.indexOf('<input type="checkbox" id="nav-trigger"');
    const headerEnd = indexContent.indexOf('</label>', indexContent.indexOf('<label for="nav-trigger" class="overlay">')) + 8;
    const header = indexContent.substring(headerStart, headerEnd);
    
    return { navigation, header };
}

// Plantilla HTML con estructura completa de JSDoc
const htmlTemplate = (title, content, navigation, header) => `<!DOCTYPE html>
<html lang="es">
<head>
    <meta charset="utf-8">
    <title>${title} - QueryBuilder API Documentation</title>
    <meta name="description" content="Documentación completa de la API QueryBuilder" />
    <meta name="keywords" content="querybuilder, sql, database, javascript, nosql, mongodb, mysql, postgresql" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    
    <script src="scripts/prettify/prettify.js"></script>
    <script src="scripts/prettify/lang-css.js"></script>
    <link type="text/css" rel="stylesheet" href="styles/prettify.css">
    <link type="text/css" rel="stylesheet" href="styles/jsdoc.css">
    <script src="scripts/nav.js" defer></script>
</head>
<body>

${header}

${navigation}

<div id="main">
    <section class="readme usertext">
        <article>
            ${content}
        </article>
    </section>
</div>

<br class="clear">

<footer>
    Documentation generated by <a href="https://github.com/jsdoc3/jsdoc">JSDoc 4.0.5</a> using the <a href="https://github.com/clenemt/docdash">docdash</a> theme.
</footer>

<script>prettyPrint();</script>
<script src="scripts/polyfill.js"></script>
<script src="scripts/linenumber.js"></script>
<script src="scripts/search.js" defer></script>
<script src="scripts/collapse.js" defer></script>

</body>
</html>`;

async function convertMarkdownFiles() {
    try {
        console.log('📝 Convirtiendo archivos Markdown a HTML...\n');
        
        // Obtener la navegación y header del index.html
        const { navigation, header } = await getNavigationTemplate();
        
        const markdownFiles = [
            'CONFIG.md',
            'CONTRIBUTING.md',
            'CODE_OF_CONDUCT.md',
            'LOCAL_PUBLISHING.md',
            'PNPM_LOCAL_SETUP.md',
            'CLEANUP-VITEPRESS.md'
        ];
        
        for (const mdFile of markdownFiles) {
            const mdPath = path.join(DOCS_DIR, mdFile);
            
            if (await fs.pathExists(mdPath)) {
                // Leer contenido markdown
                const markdown = await fs.readFile(mdPath, 'utf-8');
                
                // Convertir a HTML
                const html = marked.parse(markdown);
                
                // Extraer título (primer h1)
                const titleMatch = markdown.match(/^#\s+(.+)$/m);
                const title = titleMatch ? titleMatch[1] : path.basename(mdFile, '.md');
                
                // Generar HTML completo con navegación
                const fullHtml = htmlTemplate(title, html, navigation, header);
                
                // Guardar como HTML
                const htmlFile = mdFile.replace('.md', '.html');
                const htmlPath = path.join(DOCS_DIR, htmlFile);
                await fs.writeFile(htmlPath, fullHtml, 'utf-8');
                
                console.log(`  ✓ Convertido: ${mdFile} → ${htmlFile}`);
            }
        }
        
        console.log('\n✅ Conversión completada\n');
        
    } catch (error) {
        console.error('❌ Error convirtiendo archivos:', error.message);
        process.exit(1);
    }
}

convertMarkdownFiles();
